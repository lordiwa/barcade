namespace Barcade.Core
{
    /// <summary>
    /// The four fixed player slots on the arcade cabinet.
    /// The integer value of each member is also the player index (0–3).
    /// Color names follow the project's Spanish primary-color vocabulary.
    /// </summary>
    public enum PlayerSlot
    {
        Rojo     = 0,
        Azul     = 1,
        Amarillo = 2,
        Verde    = 3,
    }
}
